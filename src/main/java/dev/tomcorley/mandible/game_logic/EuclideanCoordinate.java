package dev.tomcorley.mandible.game_logic;

public class EuclideanCoordinate {
    private final double x;
    private final double y;

    public EuclideanCoordinate(double x, double y) {
        this.x = x;
        this.y = y;
    }

    public double getX() {
        return x;
    }   

    public double getY() {
        return y;
    }
}
